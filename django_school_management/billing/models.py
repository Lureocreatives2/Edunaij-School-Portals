class StripeCustomer(models.Model):
    """Links a Tenant to their Stripe Customer profile."""
    tenant = models.OneToOneField(Tenant, on_delete=models.CASCADE, related_name='stripe_customer')
    stripe_customer_id = models.CharField(max_length=255, unique=True)
    payment_method_id = models.CharField(max_length=255, blank=True, null=True, help_text="Stripe PM ID (e.g., pm_123)")
    email_for_payments = models.EmailField()
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Stripe Customer: {self.tenant.name} ({self.stripe_customer_id})"


class Subscription(models.Model):
    """Tracks the active subscription state of a Tenant."""
    STATUS_CHOICES = [
        ('active', 'Active'),
        ('past_due', 'Past Due'),
        ('canceled', 'Canceled'),
        ('paused', 'Paused'),
        ('incomplete', 'Incomplete'),
    ]
    
    tenant = models.OneToOneField(Tenant, on_delete=models.CASCADE, related_name='subscription')
    # billing_plan = models.ForeignKey('billing.BillingPlan', on_delete=models.PROTECT) # Uncomment when BillingPlan is ready
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='incomplete')
    stripe_subscription_id = models.CharField(max_length=255, unique=True, blank=True, null=True)
    current_period_start = models.DateTimeField(null=True, blank=True)
    current_period_end = models.DateTimeField(null=True, blank=True)
    auto_renew = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Subscription: {self.tenant.name} ({self.status})"


class Invoice(models.Model):
    """Records individual invoices generated by Stripe."""
    STATUS_CHOICES = [
        ('draft', 'Draft'),
        ('open', 'Open'),
        ('paid', 'Paid'),
        ('void', 'Void'),
        ('uncollectible', 'Uncollectible'),
    ]
    
    tenant = models.ForeignKey(Tenant, on_delete=models.CASCADE, related_name='invoices')
    subscription = models.ForeignKey(Subscription, on_delete=models.SET_NULL, null=True, blank=True, related_name='invoices')
    stripe_invoice_id = models.CharField(max_length=255, unique=True)
    amount = models.DecimalField(max_digits=10, decimal_places=2, help_text="Amount in NGN")
    currency = models.CharField(max_length=3, default='NGN')
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='open')
    paid_at = models.DateTimeField(null=True, blank=True)
    due_date = models.DateTimeField(null=True, blank=True)
    description = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Invoice {self.stripe_invoice_id} - {self.tenant.name}"


class UsageRecord(models.Model):
    """Tracks metered usage for quota enforcement and billing disputes."""
    METRIC_CHOICES = [
        ('students', 'Active Students'),
        ('teachers', 'Active Teachers'),
        ('classes', 'Active Classes'),
    ]
    
    tenant = models.ForeignKey(Tenant, on_delete=models.CASCADE, related_name='usage_records')
    metric = models.CharField(max_length=20, choices=METRIC_CHOICES)
    count = models.PositiveIntegerField()
    recorded_at = models.DateTimeField(auto_now_add=True)
    period_start = models.DateField()
    period_end = models.DateField()

    class Meta:
        ordering = ['-recorded_at']
        unique_together = ['tenant', 'metric', 'period_start', 'period_end']

    def __str__(self):
        return f"{self.tenant.name} - {self.metric}: {self.count}"
